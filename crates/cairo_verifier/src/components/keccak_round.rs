// Written by hand: generated, this component's 3049 constraints over 2402 columns unroll into one
// function too large to compile well. The columns, constraints and relation entries are those of
// the AIR `airs::casm::builtins::keccak::keccak_round::KeccakRound`, in the same order, which
// `test_evaluation_result` checks against the compiled AIR's sample evaluation.

use std::array::from_fn;

use stwo_cairo_common::keccak::{
    IOTA_BITS, N_LIMBS, N_ROUNDS, RHO_OFFSETS, bit_of_limb, limb_len, pi_source, round_constant_bit,
};

use super::prelude::*;

pub const N_TRACE_COLUMNS: usize = 2402;
pub const N_INTERACTION_COLUMNS: usize = 4;

pub const RELATION_USES_PER_ROW: [RelationUse; 1] =
    [RelationUse { relation_id: "KeccakRound", uses: 1 }];

/// The id the AIR infra derives for the `KeccakRound` relation from its name.
const KECCAK_ROUND_RELATION_ID: u32 = 384052509;

/// `a ^ b` for bits, as `a + b (1 - 2a)`.
fn xor<Value: IValue>(context: &mut Context<Value>, a: Var, b: Var) -> Var {
    eval!(context, (a) + ((b) * ((1) - ((2) * (a)))))
}

/// `b0 ^ (!b1 & b2)` for bits, the chi step, as `b0 + (1 - b1) b2 (1 - 2 b0)`.
fn chi<Value: IValue>(context: &mut Context<Value>, b0: Var, b1: Var, b2: Var) -> Var {
    eval!(context, (b0) + ((((1) - (b1)) * (b2)) * ((1) - ((2) * (b0)))))
}

/// `a * (a - 1)`, zero exactly on bits.
fn bit<Value: IValue>(context: &mut Context<Value>, a: Var) -> Var {
    eval!(context, (a) * ((a) - (1)))
}

fn sum<Value: IValue>(context: &mut Context<Value>, terms: impl IntoIterator<Item = Var>) -> Var {
    terms.into_iter().reduce(|acc, term| eval!(context, (acc) + (term))).unwrap()
}

/// `sum_i 2^i bits[i]`.
fn pack<Value: IValue>(context: &mut Context<Value>, bits: Vec<Var>) -> Var {
    let terms: Vec<Var> = bits
        .into_iter()
        .enumerate()
        .map(|(position, b)| {
            let power = context.constant((1u32 << position).into());
            eval!(context, (power) * (b))
        })
        .collect();
    sum(context, terms)
}

#[allow(unused_variables)]
pub fn accumulate_constraints<Value: IValue>(
    input: &[Var],
    context: &mut Context<Value>,
    component_data: &dyn ComponentDataTrait<Value>,
    acc: &mut CompositionConstraintAccumulator,
) {
    assert_eq!(input.len(), N_TRACE_COLUMNS);
    let mut columns = input.iter().copied();
    let mut next = || columns.next().unwrap();
    let enabler = next();
    let chain = next();
    let round = next();
    let input_limbs: [Var; N_LIMBS] = from_fn(|_| next());
    let selectors: [Var; N_ROUNDS] = from_fn(|_| next());
    // Indexed [x][z], then [x][y][z].
    let c: [[Var; 64]; 5] = from_fn(|_| from_fn(|_| next()));
    let c_prime: [[Var; 64]; 5] = from_fn(|_| from_fn(|_| next()));
    let a_prime: [[[Var; 64]; 5]; 5] = from_fn(|_| from_fn(|_| from_fn(|_| next())));
    let chi_bits: [Var; IOTA_BITS.len()] = from_fn(|_| next());
    let output: [Var; N_LIMBS] = from_fn(|_| next());

    let constraint = eval!(context, ((enabler) * (enabler)) - (enabler));
    acc.add_constraint(context, constraint);

    // The round constant comes from a one-hot selector of the round number.
    for &selector in &selectors {
        let constraint = bit(context, selector);
        acc.add_constraint(context, constraint);
    }
    let one_hot = sum(context, selectors);
    let constraint = eval!(context, (one_hot) - (1));
    acc.add_constraint(context, constraint);
    let index_terms: Vec<Var> = (1..N_ROUNDS)
        .map(|i| {
            let weight = context.constant((i as u32).into());
            eval!(context, (weight) * (selectors[i]))
        })
        .collect();
    let index = sum(context, index_terms);
    let constraint = eval!(context, (index) - (round));
    acc.add_constraint(context, constraint);

    for &b in c.iter().chain(&c_prime).chain(a_prime.iter().flatten()).flatten() {
        let constraint = bit(context, b);
        acc.add_constraint(context, constraint);
    }

    // Theta: d[x][z] = c[x-1][z] ^ c[x+1][z-1]; c' = c ^ d, and a' down a column has parity c'.
    let mut theta = [[context.zero(); 64]; 5];
    for (x, row) in theta.iter_mut().enumerate() {
        for (z, term) in row.iter_mut().enumerate() {
            *term = xor(context, c[(x + 4) % 5][z], c[(x + 1) % 5][(z + 63) % 64]);
        }
    }
    for x in 0..5 {
        for z in 0..64 {
            let c_xor_theta = xor(context, c[x][z], theta[x][z]);
            let constraint = eval!(context, (c_prime[x][z]) - (c_xor_theta));
            acc.add_constraint(context, constraint);
            let column = sum(context, (0..5).map(|y| a_prime[x][y][z]));
            let diff = eval!(context, (column) - (c_prime[x][z]));
            let constraint = eval!(context, ((diff) * ((diff) - (2))) * ((diff) - (4)));
            acc.add_constraint(context, constraint);
        }
    }

    // The input limbs are the bits a' ^ d.
    for (limb, &input_limb) in input_limbs.iter().enumerate() {
        let bits: Vec<Var> = (0..limb_len(limb))
            .map(|position| {
                let k = bit_of_limb(limb, position);
                let (lane, z) = (k / 64, k % 64);
                let (x, y) = (lane % 5, lane / 5);
                xor(context, a_prime[x][y][z], theta[x][z])
            })
            .collect();
        let value = pack(context, bits);
        let constraint = eval!(context, (input_limb) - (value));
        acc.add_constraint(context, constraint);
    }

    // Rho and pi: bit z of lane (x, y) is bit z - rho of a'[x0][y0].
    let b = |x: usize, y: usize, z: usize| -> Var {
        let (x0, y0) = pi_source(x, y);
        a_prime[x0][y0][(z + 64 - RHO_OFFSETS[x0][y0]) % 64]
    };

    // Chi, and iota on the 7 bits of lane (0, 0) that a round constant can set.
    for (j, &chi_bit) in chi_bits.iter().enumerate() {
        let z = IOTA_BITS[j];
        let constraint = bit(context, chi_bit);
        acc.add_constraint(context, constraint);
        let value = chi(context, b(0, 0, z), b(1, 0, z), b(2, 0, z));
        let constraint = eval!(context, (chi_bit) - (value));
        acc.add_constraint(context, constraint);
    }
    for (limb, &output_limb) in output.iter().enumerate() {
        let bits: Vec<Var> = (0..limb_len(limb))
            .map(|position| {
                let k = bit_of_limb(limb, position);
                let (lane, z) = (k / 64, k % 64);
                let (x, y) = (lane % 5, lane / 5);
                match IOTA_BITS.iter().position(|&iota| lane == 0 && iota == z) {
                    Some(j) => {
                        let round_constant = sum(
                            context,
                            (0..N_ROUNDS)
                                .filter(|&i| round_constant_bit(i, j))
                                .map(|i| selectors[i]),
                        );
                        xor(context, chi_bits[j], round_constant)
                    }
                    None => chi(context, b(x, y, z), b((x + 1) % 5, y, z), b((x + 2) % 5, y, z)),
                }
            })
            .collect();
        let value = pack(context, bits);
        let constraint = eval!(context, (output_limb) - (value));
        acc.add_constraint(context, constraint);
    }

    // Use KeccakRound.
    let relation_id = context.constant(KECCAK_ROUND_RELATION_ID.into());
    let tuple: Vec<Var> = [relation_id, chain, round].into_iter().chain(input_limbs).collect();
    let numerator = eval!(context, enabler);
    acc.add_to_relation(context, numerator, &tuple);

    // Yield KeccakRound.
    let next_round = eval!(context, (round) + (1));
    let tuple: Vec<Var> = [relation_id, chain, next_round].into_iter().chain(output).collect();
    let numerator = eval!(context, -(enabler));
    acc.add_to_relation(context, numerator, &tuple);
}

pub struct Component {}
impl<Value: IValue> CircuitEval<Value> for Component {
    fn name(&self) -> String {
        "keccak_round".to_string()
    }

    fn evaluate(
        &self,
        context: &mut Context<Value>,
        component_data: &dyn ComponentDataTrait<Value>,
        acc: &mut CompositionConstraintAccumulator,
    ) {
        accumulate_constraints(component_data.trace_columns(), context, component_data, acc);
    }

    fn trace_columns(&self) -> usize {
        N_TRACE_COLUMNS
    }

    fn interaction_columns(&self) -> usize {
        N_INTERACTION_COLUMNS
    }

    fn relation_uses_per_row(&self) -> &[RelationUse] {
        &RELATION_USES_PER_ROW
    }

    fn log_size(
        &self,
        _preprocessed_column_log_sizes: &OrderedHashMap<PreProcessedColumnId, u32>,
    ) -> Option<u32> {
        None
    }
}
